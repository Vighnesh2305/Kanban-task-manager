// Mock localStorage
const localStorageMock = (() => {
  let store: Record<string, string> = {};
  return {
    getItem: vi.fn((key: string) => (key in store ? store[key] : null)),
    setItem: vi.fn((key: string, value: string) => {
      store[key] = String(value);
    }),
    removeItem: vi.fn((key: string) => {
      delete store[key];
    }),
    clear: vi.fn(() => {
      store = {};
    }),
    key: vi.fn((index: number) => Object.keys(store)[index] || null),
    get length() {
      return Object.keys(store).length;
    },
  };
})();

Object.defineProperty(window, 'localStorage', {
  value: localStorageMock,
  writable: true,
});
Object.defineProperty(global, 'localStorage', {
  value: localStorageMock,
  writable: true,
});

// Mock BroadcastChannel
class MockBroadcastChannel {
  name: string;
  onmessage: ((event: MessageEvent) => void) | null = null;
  static channels: Record<string, MockBroadcastChannel[]> = {};

  constructor(name: string) {
    this.name = name;
    if (!MockBroadcastChannel.channels[name]) {
      MockBroadcastChannel.channels[name] = [];
    }
    MockBroadcastChannel.channels[name].push(this);
  }

  postMessage(message: any) {
    const subs = MockBroadcastChannel.channels[this.name] || [];
    subs.forEach(ch => {
      if (ch !== this && ch.onmessage) {
        ch.onmessage(new MessageEvent('message', { data: message }));
      }
    });
  }

  close() {
    const list = MockBroadcastChannel.channels[this.name] || [];
    MockBroadcastChannel.channels[this.name] = list.filter(ch => ch !== this);
  }
}

(window as any).BroadcastChannel = MockBroadcastChannel;
(global as any).BroadcastChannel = MockBroadcastChannel;
